-- Farmer Selling Survey: schema, tables and an app role. Run once as ACCOUNTADMIN.
CREATE SCHEMA IF NOT EXISTS JSA.FARMER_SURVEY;

CREATE TABLE IF NOT EXISTS JSA.FARMER_SURVEY.MONTHLY (
    COMMODITY  VARCHAR NOT NULL,
    KIND       VARCHAR NOT NULL,   -- current | new
    CROP_YEAR  VARCHAR NOT NULL,   -- e.g. 26/27
    MONTH      VARCHAR NOT NULL,   -- Jan..Dec, or 'Jun close' for the wheat year-end row
    PCT        FLOAT   NOT NULL,   -- 0-100
    UPDATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (COMMODITY, KIND, CROP_YEAR, MONTH)
);

CREATE TABLE IF NOT EXISTS JSA.FARMER_SURVEY.SURVEYS (
    COMMODITY   VARCHAR NOT NULL,
    CROP_YEAR   VARCHAR NOT NULL,
    SURVEY_DATE DATE    NOT NULL,
    PCT         FLOAT   NOT NULL
);

-- App role: read both tables, write MONTHLY only (the Admin tab).
CREATE ROLE IF NOT EXISTS FARMER_SURVEY_ROLE;
GRANT USAGE ON DATABASE JSA TO ROLE FARMER_SURVEY_ROLE;
GRANT USAGE ON SCHEMA JSA.FARMER_SURVEY TO ROLE FARMER_SURVEY_ROLE;
GRANT SELECT ON ALL TABLES IN SCHEMA JSA.FARMER_SURVEY TO ROLE FARMER_SURVEY_ROLE;
GRANT SELECT ON FUTURE TABLES IN SCHEMA JSA.FARMER_SURVEY TO ROLE FARMER_SURVEY_ROLE;
GRANT INSERT, UPDATE, DELETE ON TABLE JSA.FARMER_SURVEY.MONTHLY TO ROLE FARMER_SURVEY_ROLE;
GRANT USAGE ON WAREHOUSE COMPUTE_WH TO ROLE FARMER_SURVEY_ROLE;

