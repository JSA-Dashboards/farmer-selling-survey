-- Client-facing monthly survey: access codes + responses. Run once as ACCOUNTADMIN (after setup.sql).
CREATE TABLE IF NOT EXISTS JSA.FARMER_SURVEY.CLIENTS (
    CLIENT_ID  VARCHAR NOT NULL,
    NAME       VARCHAR NOT NULL,
    CODE_HASH  VARCHAR NOT NULL,          -- SHA-256 of the access code; the code itself is never stored
    ACTIVE     BOOLEAN DEFAULT TRUE,
    CREATED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (CLIENT_ID)
);

CREATE TABLE IF NOT EXISTS JSA.FARMER_SURVEY.RESPONSES (
    CLIENT_ID    VARCHAR NOT NULL,
    MONTH_KEY    VARCHAR NOT NULL,         -- YYYY-MM
    COMMODITY    VARCHAR NOT NULL,
    KIND         VARCHAR NOT NULL,         -- current | new
    CROP_YEAR    VARCHAR NOT NULL,
    PCT          FLOAT   NOT NULL,         -- 0-100
    SUBMITTED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
    PRIMARY KEY (CLIENT_ID, MONTH_KEY, COMMODITY, KIND)
);

-- The dashboard app (FARMER_SURVEY_ROLE) and the admin portal mirror (ADMIN_PORTAL_ROLE) both
-- serve the form and the Admin tab.
GRANT SELECT, INSERT, UPDATE ON TABLE JSA.FARMER_SURVEY.CLIENTS   TO ROLE FARMER_SURVEY_ROLE;
GRANT SELECT, INSERT, UPDATE ON TABLE JSA.FARMER_SURVEY.RESPONSES TO ROLE FARMER_SURVEY_ROLE;
GRANT SELECT, INSERT, UPDATE ON TABLE JSA.FARMER_SURVEY.CLIENTS   TO ROLE ADMIN_PORTAL_ROLE;
GRANT SELECT, INSERT, UPDATE ON TABLE JSA.FARMER_SURVEY.RESPONSES TO ROLE ADMIN_PORTAL_ROLE;
